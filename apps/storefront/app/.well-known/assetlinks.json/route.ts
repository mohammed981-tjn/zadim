// ⚠️ يُقرأ وقتَ الطلب لا وقتَ البناء: البصمةُ تُضاف في Vercel **بعد**
// أوّل رفعٍ إلى Play، ولو خُبزت في البناء لاحتاجت إعادةَ نشرٍ ليراها أحد.
export const dynamic = "force-dynamic"

const PACKAGE = process.env.ANDROID_PACKAGE_NAME ?? "co.zadim.store"

export async function GET() {
  const raw = process.env.ANDROID_CERT_SHA256 ?? ""
  // فاصلتان مقبولتان (`,` وسطرٌ جديد) لأن Play يعرض البصمتين — بصمةَ
  // مفتاح الرفع وبصمةَ مفتاح التوقيع — وتُلصقان كما هما.
  const fingerprints = raw
    .split(/[\s,]+/)
    .map((f) => f.trim().toUpperCase())
    .filter((f) => /^([0-9A-F]{2}:){31}[0-9A-F]{2}$/.test(f))

  if (fingerprints.length === 0) {
    return Response.json(
      {
        error: {
          code: "ANDROID_CERT_SHA256_MISSING",
          message_ar:
            "لم تُضبط ANDROID_CERT_SHA256. أضفْ بصمةَ SHA-256 لمفتاح التوقيع " +
            "(بالصيغة AB:CD:… اثنتين وثلاثين خانة) في متغيّرات البيئة، ثم أعد المحاولة.",
        },
      },
      { status: 404 },
    )
  }

  return Response.json(
    [
      {
        relation: ["delegate_permission/common.handle_all_urls"],
        target: {
          namespace: "android_app",
          package_name: PACKAGE,
          sha256_cert_fingerprints: fingerprints,
        },
      },
    ],
    // النوعُ مقصود: Chrome يقبل `application/json`، وهو ما يجعل الملفَّ
    // مقروءاً في المتصفّح أيضاً عند التشخيص.
    { headers: { "content-type": "application/json" } },
  )
}
