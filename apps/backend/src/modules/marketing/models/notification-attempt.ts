import { model } from "@medusajs/framework/utils";

/**
 * دفترُ المحاولات — **الطرفُ الذي كان ناقصاً في «الإشعارات الموثوقة»**.
 *
 * ── ما كان يقع قبل هذا الجدول ────────────────────────────────────
 *
 * `zadim_notification_send` يحمل **آخرَ** حالةٍ وحدَها. فرسالةٌ فشلت
 * أربعَ مرّاتٍ ثم نجحت تبدو كرسالةٍ نجحت من أوّل مرّة، ورسالةٌ تفشل
 * منذ يومين تبدو كرسالةٍ فشلت الآن. **ولا سبيلَ إلى «لماذا لم تصل»**
 * لأن أسبابَ الفشل تُكتب فوق بعضها في حقلٍ واحد.
 *
 * وهذا ليس نقصَ تقارير: هو الفرقُ بين مزوّدٍ يرفض عنواناً بعينه (يُشطب
 * المستقبِل) ومزوّدٍ سقط عشرَ دقائق (تُعاد المحاولة). والحقلُ الواحدُ
 * يُظهر الاثنين سواءً.
 *
 * ── ولماذا يُلحَق ولا يُمسّ ─────────────────────────────────────
 *
 * لأنه دفترُ وقائع كسجلّ التدقيق وحركاتِ المخزون وإيصالاتِ الشراء:
 * محاولةٌ وقعت لا تُحذَف ولا تُعدَّل. والتصحيحُ **بصفٍّ مقابل** لا
 * بمسحِ الماضي. وقاعدةُ `do instead nothing` تجعل ذلك بنيةً لا عادة.
 *
 * ── و`attempt_no` تحسبه القاعدة ─────────────────────────────────
 *
 * 🔴 لا التطبيق. فمُشغِّلان يعيدان نفسَ الرسالةَ في نفس اللحظة
 * يقرآن «آخرُ محاولةٍ ٢» معاً فيكتبان ٣ معاً. والمُطلِقُ يحسبها تحت
 * قفلِ صفّ الأب، **والفهرسُ الفريد (send_id · attempt_no) هو الحكم**
 * لا نيّةُ الكود.
 */
export const NotificationAttempt = model
  .define("zadim_notification_attempt", {
    id: model.id({ prefix: "natt" }).primaryKey(),

    send_id: model.text(),

    /**
     * ⚠️ `0` لا لأنها قيمةٌ صالحة بل لأن MikroORM يتحقّق **قبل** أن
     * يعمل المُطلِق. والقيدُ `>= 1` في القاعدة يجعلها تسقط بصوتٍ عالٍ
     * لو اختفى المُطلِقُ يوماً — بدل أن تُكتب أصفارٌ صامتة.
     */
    attempt_no: model.number().default(0),

    /** حالةُ المزوّد كما قالها — لا تُترجَم (`notify/contract.ts`). */
    status: model.text(),
    provider: model.text().nullable(),
    error: model.text().nullable(),
  })
  .indexes([{ on: ["send_id"] }]);

export default NotificationAttempt;
