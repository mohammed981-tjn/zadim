import { model } from "@medusajs/framework/utils";

/**
 * سياسةُ إقفالِ الحساب بعد فشلٍ متكرّر — **صفٌّ يضبطه المدير**.
 *
 * ── الثغرةُ التي تسدّها، وحدُّ المعدّل لا يسدّها ──────────────────
 *
 * `zadim_rate_limit_policy` يحدّ `/auth` بعشر محاولاتٍ في الدقيقة
 * **بالعنوان**. وذاك يوقف من يجرّب ألفَ كلمةٍ من حاسوبه. ولا يوقف
 * **شبكةً بعشرة آلاف عنوان** تجرّب حساباً واحداً: لكلّ عنوانٍ عشرٌ في
 * الدقيقة، فمئةُ ألفِ محاولةٍ في الدقيقة على حسابٍ واحد — وكلُّها
 * تحت الحدّ.
 *
 * فالمفتاحُ هنا **الهويّةُ لا العنوان**.
 *
 * ── ⚠️ والمقايضةُ تُقال صراحةً: إقفالٌ يُساء استعماله ────────────
 *
 * من عرف بريدَ عميلٍ يستطيع أن يُفشل الدخولَ مرّاتٍ فيقفل حسابَه
 * مؤقّتاً — **حرمانُ خدمةٍ ضدّ الضحية**. وهي مقايضةٌ معروفةٌ يوصي
 * بقبولها OWASP بشرطين نُفِّذا:
 *
 * ١. **الإقفالُ مؤقّتٌ بمدّةٍ يضبطها المدير**، لا دائمٌ يحتاج دعماً.
 * ٢. **الدفترُ يحمل العناوين**، فيُميَّز «عميلٌ نسي» من «هجومٌ موزَّع»
 *    بنظرةٍ واحدة.
 *
 * ── ولا رقمَ مبرمَجٌ في الكود (بند ٤٨) ──────────────────────────
 *
 * ولا صفَّ ⇒ **لا إقفال**. وهو فشلٌ مفتوحٌ بقصد، لنفس سبب
 * `rate-limit.ts`: جدولٌ مفقودٌ يجب ألّا يمنع الناسَ من الدخول إلى
 * متجرهم. والحارسُ ضدّ نسيانِ الصفّ بذرةٌ تُنشئه وبوّابةٌ تقيسه.
 */
export const LockoutPolicy = model.define("zadim_lockout_policy", {
  id: model.id({ prefix: "lop" }).primaryKey(),

  /** `user` للإدارة و`customer` للمتجر — صفٌّ لكلٍّ. */
  actor_type: model.enum(["user", "customer"]),

  /** نافذةُ العدّ بالثواني: كم مضى من الزمن يُنظر فيه إلى الفشل. */
  window_seconds: model.number(),

  /** كم فشلاً في النافذة قبل الإقفال. */
  max_failures: model.number(),

  /** مدّةُ الإقفال بالثواني، تُحسب من **آخر** فشل. */
  lock_seconds: model.number(),

  /** مفتاحُ إطفاءٍ — لنفس سبب `RateLimitPolicy.enabled`. */
  enabled: model.boolean().default(true),
});

export default LockoutPolicy;
