import { model } from "@medusajs/framework/utils";

/**
 * سياسةُ تحديدِ معدّل — كم نداءً يُسمح به، لأيّ مسارٍ، في أيّ نافذة.
 *
 * ── لماذا صفوفٌ لا ثوابتُ في الكود ────────────────────────────────
 *
 * لأن الرقمَ الصحيحَ لا يُعرف قبل الإطلاق: خمسُ محاولاتِ دخولٍ في
 * الدقيقة قد تكون كرماً أو خنقاً، ولا يُحسم إلا بالمشاهدة. ورقمٌ
 * مبرمَجٌ يعني أن ضبطَه **نشرةٌ كاملة** — فيُترك خاطئاً لأن تصحيحه
 * أغلى من ضرره، حتى يصير الحارسُ زينة.
 *
 * وهو أيضاً بندُ البوّابة العامّة نصّاً: «صفرُ قاعدةِ عملٍ مبرمَجة».
 *
 * ── والمسارُ سابقةٌ لا تعبيرٌ منتظم ──────────────────────────────
 *
 * صفٌّ في القاعدة يكتبه مديرٌ لا مبرمج. وتعبيرٌ منتظمٌ مكتوبٌ بيدٍ
 * غيرِ خبيرة يفتح بابين: نمطٌ لا يُطابق شيئاً فيسقط الحارسُ صامتاً،
 * ونمطٌ كارثيُّ التراجع (ReDoS) يُعلّق الخادمَ بطلبٍ واحد. والسابقةُ
 * (`startsWith`) تعجز عن أشياء — وتعجز أيضاً عن أن تؤذي.
 */
export const RateLimitPolicy = model.define("zadim_rate_limit_policy", {
  id: model.id({ prefix: "rlp" }).primaryKey(),

  /** اسمٌ فريد — وهو مفتاحُ العدّادات، فتغييرُه يبدأ نافذةً جديدة. */
  name: model.text(),

  /** سابقةُ المسار كما يصل: `/auth`، `/store/carts`، `/admin`. */
  path_prefix: model.text(),

  /**
   * الأفعالُ المحكومة، مفصولةً بفاصلة، أو `*` لكلّها.
   *
   * ولماذا لا تُحكم كلُّ الأفعال دائماً: قراءةُ صفحةِ منتجٍ ليست
   * محاولةَ دخول. وحدٌّ واحدٌ يجمعهما إمّا يخنق التصفّح وإمّا يترك
   * التخمين — فيُفصل الفعلُ ليُفصل الرقم.
   */
  methods: model.text().default("*"),

  /** طولُ النافذة بالثواني. */
  window_seconds: model.number(),

  /** أقصى عددِ نداءاتٍ في النافذة الواحدة لكل مفتاح. */
  max_requests: model.number(),

  /**
   * على أيّ شيءٍ يُحسب العدّاد.
   *
   * `ip` — للمجهول (تخمينُ كلمة المرور قبل أن تُعرف هويةُ أحد).
   * `actor` — للمعروف (حسابٌ مسروقٌ يستنزف من داخل الجلسة).
   * `ip_actor` — الاثنان معاً، فمن بدّل الشبكة لم يُفلت، ومن بدّل
   *              الحساب لم يُفلت.
   */
  scope_by: model.enum(["ip", "actor", "ip_actor"]).default("ip"),

  /**
   * مفتاحُ إطفاءٍ لكل سياسةٍ على حدة.
   *
   * وسببُه واقعةٌ متوقَّعة لا احتمالٌ نظريّ: حدٌّ ضيّقٌ يُطلق يومَ ذروةٍ
   * فيُوقف الشراء. وحذفُ الصفّ يفقد رقمَه المضبوط، والإطفاءُ يُبقيه
   * حتى يُراجَع.
   */
  enabled: model.boolean().default(true),
});
