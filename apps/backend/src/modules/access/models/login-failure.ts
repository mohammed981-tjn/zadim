import { model } from "@medusajs/framework/utils";

/**
 * دفترُ محاولاتِ الدخول الفاشلة — **يُلحَق ولا يُمسّ**.
 *
 * ── لماذا دفترٌ لا عدّاد ─────────────────────────────────────────
 *
 * نفسُ الدرس المدفوعِ ثمنُه مرّتين في هذا المستودع: العدّادُ حقلٌ
 * مشتقٌّ يفسده التزاحمُ فيقول رقماً والقيدُ يمرّ
 * (`Migration20260901000002`: ٩٤ بيعاً من عشرة). والمتبقّي هنا
 * **يُجمع من الصفوف** في كل فحص.
 *
 * وله فائدةٌ ثانيةٌ لا يعطيها العدّاد: **العنوانُ مُسجَّلٌ مع كل فشل**،
 * فيرى المديرُ هل جاءت المحاولاتُ من مصدرٍ واحدٍ أم من ألف — وهو
 * الفارقُ بين عميلٍ نسي كلمتَه وبين هجومٍ موزَّع.
 *
 * ── ولماذا الفشلُ وحدَه يُقيَّد لا كلُّ محاولة ───────────────────
 *
 * لأن عدَّ كلِّ المحاولات يقفل حسابَ من فتح التطبيقَ في لسانَي متصفّحٍ
 * ودخل مرّتين. والإشارةُ التي تدلّ على التخمين هي **الفشلُ المتكرّر**
 * لا النشاط.
 */
export const LoginFailure = model.define("zadim_login_failure", {
  id: model.id({ prefix: "lgf" }).primaryKey(),

  /**
   * الهويّةُ المحاوَلة، **مطبَّعةً** (بريدٌ بحروفٍ صغيرة).
   *
   * وبلا تطبيعٍ يكون `A@b.co` و`a@b.co` حسابين في نظر الحدّ — فيُجرَّب
   * كلُّ حسابٍ ضِعفَ الحدّ بتغيير حالة حرفٍ واحد.
   */
  identity_key: model.text(),

  /** `user` للإدارة و`customer` للمتجر — ولكلٍّ سياستُه. */
  actor_type: model.enum(["user", "customer"]),

  /** عنوانُ المحاوِل كما حسبه `clientIp` — للتشخيص لا للحكم. */
  ip: model.text().nullable(),

  user_agent: model.text().nullable(),
});

export default LoginFailure;
