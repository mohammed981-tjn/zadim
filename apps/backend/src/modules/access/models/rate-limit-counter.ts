import { model } from "@medusajs/framework/utils";

/**
 * عدّادُ نافذةٍ واحدة: كم نداءً وصل من هذا المفتاح لهذه السياسة في
 * هذه النافذة.
 *
 * ── 🔴 لماذا في القاعدة لا في ذاكرة العملية ──────────────────────
 *
 * عدّادٌ في الذاكرة **يُصفَّر مع كل نشرة**. فمن أراد تجاوزَ الحدّ لا
 * يحتاج أن يهزمه: ينتظر أوّلَ نشرةٍ فيُمحى. وأسوأُ منه أن الحارسَ
 * **يضعف بلا صوت** يومَ تصير النسخُ نسختين: كلُّ نسخةٍ تعدّ وحدَها،
 * فيصير الحدُّ ضعفَ ما كُتب — والبوّابةُ خضراءُ والرقمُ في اللوحة كما
 * هو. وحارسٌ يضعف صامتاً أخطرُ من حارسٍ غائبٍ يُرى غيابُه.
 *
 * وثمنُه كتابةٌ واحدةٌ في الطلب — تُدفع على المسارات الحسّاسة وحدها
 * (`/auth` والشراء والإدارة)، لا على تصفّح المنتجات.
 *
 * ── ونافذةٌ ثابتةٌ لا منزلقة — يُقال ولا يُخفى ────────────────────
 *
 * النافذةُ الثابتة تسمح بضِعف الحدّ على الحافّة: عشرُ محاولاتٍ آخرَ
 * الدقيقة الأولى وعشرٌ أوّلَ الثانية. والمنزلقةُ تحتاج صفّاً لكل نداء
 * (ثمنٌ لا يُحتمل) أو مجموعةً مرتّبةً في Redis (وليس لدينا Redis —
 * انظر `10-deployment.md`).
 *
 * والعلاجُ المتاح: **نافذةٌ قصيرة**. فحدُّ ٥ في الدقيقة أسوأُ حالاته
 * ١٠ في دقيقتين، وذاك بعيدٌ عن حشو بيانات الاعتماد بعشرات الآلاف.
 * وسيصير منزلقاً يومَ يأتي Redis — والمُنادي لا يتغيّر.
 */
export const RateLimitCounter = model.define("zadim_rate_limit_counter", {
  /**
   * حتميّ: `policy|scopeKey|windowStart`.
   *
   * ولماذا لا مُعرّفٌ عشوائيّ: لأن الزيادةَ يجب أن تكون **كتابةً
   * واحدةً ذرّية** (`insert … on conflict … do update … returning`).
   * ومُعرّفٌ عشوائيٌّ يجعلها قراءةً ثم كتابة، وبينهما يمرّ الطلبُ
   * الثاني — فيُقرأ العدّادُ نفسُه مرّتين ويُكتب واحداً، ويصير الحدُّ
   * بلا معنى تحت الحمل الذي وُضع له أصلاً.
   */
  id: model.text().primaryKey(),

  policy_name: model.text(),

  /** العنوان أو المُعرّف أو كلاهما — بحسب `scope_by` في السياسة. */
  scope_key: model.text(),

  /** بدايةُ النافذة، مُحاذاةً على مضاعفات `window_seconds`. */
  window_start: model.dateTime(),

  /** متى تنتهي — تُخزَّن كي يُكنس القديمُ بمقارنةٍ واحدةٍ مفهرسة. */
  expires_at: model.dateTime(),

  count: model.number().default(0),
});
