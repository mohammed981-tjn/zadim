import { model } from "@medusajs/framework/utils";

/**
 * صنفٌ في مفضّلة عميل (بند ٢٢).
 *
 * ── والبندُ ليس «قائمةَ رغبات» ───────────────────────────────────
 *
 * نصُّه: «**المفضّلة تعرف انخفاض السعر**». وقائمةٌ يفتحها العميلُ ليجد
 * أسعارَ اليوم لا تفعل شيئاً لا يفعله دفترُ روابطَ في متصفّحه. والذي
 * يفعله المتجرُ ولا يفعله المتصفّح: **أن يخبره حين يرخص ما انتظره**.
 *
 * ولذلك هذا الجدولُ ليس واجهةً فحسب: هو **قائمةُ المشتركين** التي
 * كانت ناقصةً في الطرف الآخر. فمُطلِقُ `zadim_emit_price_drop_trg`
 * يكتب حدثاً مع كلّ خفضِ سعرٍ منذ المرحلة ١١، ويقرؤه
 * `jobs/dispatch-marketing.ts` — **ولا مستقبِلَ في حمولته**، فيُخطَّط
 * صفرُ رسالة. الحدثُ كان يقع ولا أحدَ يسمعه.
 *
 * ⚠️ **ولا مفتاحَ أجنبيّ إلى `product`.** جدولُ المنتجات ليس لنا،
 * ويُحذف منه بسير عملٍ لا نملكه — ومفتاحٌ أجنبيٌّ يجعل حذفَ منتجٍ
 * يسقط أو يجرّ صفوفاً بصمت. فالصفُّ يبقى، **ويُصفّى عند القراءة**:
 * منتجٌ لم يعد موجوداً لا يُعرض ولا يُسقط الشاشة.
 */
export const WishlistItem = model
  .define("zadim_wishlist_item", {
    id: model.id({ prefix: "wish" }).primaryKey(),

    customer_id: model.text(),
    product_id: model.text(),

    /**
     * المتغيّرُ إن اختاره — وهو ما يُراقَب سعرُه.
     *
     * و`null` تعني «المنتجَ كلَّه»: أيُّ متغيّرٍ يرخص يُنبَّه صاحبُه.
     * والفرقُ يهمّ: من أراد المقاسَ L لا يريد خبراً عن رخص المقاس XS.
     */
    variant_id: model.text().nullable(),
  })
  .indexes([
    // 🔴 قيدٌ فريدٌ لا «اقرأ ثمّ اكتب» (ADR-014): ضغطتان على القلب
    // تصلان معاً فتُنشئان صفّين، ثم يصل العميلَ خبران عن خفضٍ واحد.
    // والقيدُ يجعل الثانيةَ تصطدم داخل المعاملة لا في منطقٍ يسبقها.
    { on: ["customer_id", "product_id"], unique: true, where: "deleted_at IS NULL" },
    { on: ["product_id"] },
  ]);

export default WishlistItem;
