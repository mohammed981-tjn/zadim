import { model } from "@medusajs/framework/utils";

/**
 * سطرُ قيد — **مبلغٌ موقَّعٌ على حساب**.
 *
 * ── ولماذا مبلغٌ موقَّعٌ لا عمودا مدينٍ ودائن ────────────────────
 *
 * لأن العمودين يسمحان بصفٍّ فيه الاثنان، أو فيه لا شيء — وكلاهما بلا
 * معنى، وكلاهما يحتاج قيداً إضافياً يمنعه. والمبلغُ الموقَّعُ الواحد
 * لا يقبل الحالتين أصلاً، ويجعل شرطَ التوازن **جمعاً بسيطاً إلى صفر**
 * بدل مقارنةِ مجموعين.
 *
 * والاصطلاح: **الموجبُ مدينٌ والسالبُ دائن**. ومكتوبٌ هنا لأن اصطلاحاً
 * غيرَ مكتوبٍ ينقلب بعد ستّة أشهر.
 *
 * ── والحسابُ نصٌّ لا `enum` ─────────────────────────────────────
 *
 * ⚠️ وهذا **مقصودٌ ومخالفٌ لعادة المشروع**: `enum` في النموذج يعني أن
 * إضافةَ حسابٍ محاسبيٍّ جديد هجرةٌ ونشرٌ ودفعة. والحساباتُ تنمو مع
 * العمل لا مع الكود — يومَ يصل مزوّدُ دفعٍ يلزم «رسومُ البوّابة»،
 * ويومَ تبدأ العضويةُ يلزم «إيرادٌ مؤجَّل». **ودليلُ الحسابات صفوفٌ**
 * (`zadim_ledger_account`) يحرسها مفتاحٌ أجنبيّ — فلا اسمَ يُخترع في
 * سطر كود، ولا هجرةَ لكلّ حساب.
 */
export const LedgerEntry = model
  .define("zadim_ledger_entry", {
    id: model.id({ prefix: "lent" }).primaryKey(),

    transaction_id: model.text(),

    /** مفتاحُه في `zadim_ledger_account` — والقاعدةُ تحرس وجودَه. */
    account: model.text(),

    /** بالهللات صحيحةً (ADR-008): **موجبٌ مدينٌ وسالبٌ دائن**. */
    amount: model.number(),

    currency_code: model.text(),

    note: model.text().nullable(),
  })
  .indexes([{ on: ["transaction_id"] }, { on: ["account"] }]);

export default LedgerEntry;
