import { model } from "@medusajs/framework/utils";

/**
 * قيدٌ محاسبيّ — **الحاويةُ التي يجب أن تتوازن** (البند ١٫٣).
 *
 * ── ولماذا حاويةٌ لا صفوفٌ مستقلّة ───────────────────────────────
 *
 * لأن «التوازن» خاصّةُ **مجموعةٍ** لا خاصّةُ صفّ. وصفٌّ واحدٌ بمبلغٍ
 * موجبٍ لا يخطئ ولا يصيب؛ الذي يخطئ أن يُكتب البيعُ بلا ما يقابله من
 * ضريبةٍ وذمّة. فالحارسُ يجب أن يرى المجموعةَ كلَّها — ولذلك يقع
 * **عند الالتزام** لا عند كلّ إدراج (`Migration20260904000050`).
 *
 * ── والحقولُ الستّة ليست بيروقراطية ─────────────────────────────
 *
 * «وقتٌ وفاعلٌ ومصدرٌ ومرجعٌ ومبلغٌ وعملة» — وكلُّ واحدٍ منها جوابُ
 * سؤالٍ يُسأل يومَ تختلف الأرقام:
 *
 * | الحقل | السؤالُ الذي يجيبه |
 * |---|---|
 * | `occurred_at` | متى وقع الأمرُ **فعلاً** (لا متى كُتب) |
 * | `actor_id` | من فعل — ومن لا فاعلَ له فالنظام، ويُقال |
 * | `source` | أيُّ وحدةٍ كتبته |
 * | `reference_type`/`_id` | **ما الذي يقابله في الواقع**: طلبٌ أو إيصالُ شراء |
 * | `currency_code` | ولا يُجمع قيدٌ بريالٍ إلى قيدٍ بدولار |
 *
 * ⚠️ **ولا يُعدَّل ولا يُحذف**: التصحيحُ بقيدٍ مقابل. ودفترٌ يُعدَّل
 * ليس دفتراً — هو رأيٌ عن الماضي.
 */
export const LedgerTransaction = model
  .define("zadim_ledger_transaction", {
    id: model.id({ prefix: "ltx" }).primaryKey(),

    /** بيع · دفع · استرداد · دفعةُ مورّد · ولاء · تسوية. */
    kind: model.text(),

    source: model.text(),
    reference_type: model.text(),
    reference_id: model.text(),

    /** من لا فاعلَ له فالنظام — و`null` تعني ذلك صراحةً. */
    actor_id: model.text().nullable(),

    currency_code: model.text(),
    occurred_at: model.dateTime(),

    note: model.text().nullable(),
  })
  .indexes([
    { on: ["reference_type", "reference_id"] },
    { on: ["kind"] },
  ]);

export default LedgerTransaction;
