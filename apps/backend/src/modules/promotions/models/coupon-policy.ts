import { model } from "@medusajs/framework/utils";

/**
 * سياسةُ كوبونٍ عندنا — **ما لا يملكه محرّكُ Medusa** (بندا ٢٦ و٢٧).
 *
 * ── ما قِيس على Medusa 2.19 قبل كتابة سطرٍ من هذا ─────────────────
 *
 * يملك المحرّكُ فعلاً: `code` بفهرسٍ فريد · `is_automatic` (فصلُ العرض
 * عن الكوبون **بنيةً لا اصطلاحاً** — بند ٢٧) · `promotion_rule` صفوفاً
 * بـ(حقل، مُعامل، قيم) وهو نصُّ «القواعد بيانات لا كود» · حملاتٍ
 * بنوافذَ زمنيةٍ وميزانيات · حدّاً كلّياً (`limit`/`used`) **بقفلِ صفٍّ
 * حقيقيٍّ قبل الزيادة**.
 *
 * فلا يُعاد بناءُ شيءٍ من ذلك — نظاما عروضٍ يفترقان عند أوّل تعارض.
 *
 * ── وثلاثةٌ لا يملكها، وكلُّها ثقوبٌ حقيقية ──────────────────────
 *
 * ١. **الحدُّ لكل عميل.** `limit` عدّادٌ كلّيّ: يمنع «ألفَ استخدامٍ
 *    إجمالاً» ولا يمنع أن يكون الألفُ كلُّه لواحد. وهذا هو الحدُّ الذي
 *    تُساء به الكوبوناتُ فعلاً.
 *
 * ٢. 🔴 **سقفُ الخصم بالمال.** قِيس أن `application_method.max_quantity`
 *    سقفُ **كمية** لا سقفُ مال — ولا سقفَ ماليٍّ في المحرّك إطلاقاً.
 *    فكوبونُ «٥٠٪» على سلّةٍ بعشرة آلافِ ريالٍ يخصم خمسةَ آلاف. وهو
 *    الفرقُ بين عرضٍ تسويقيٍّ وبابِ نزفٍ للخزينة.
 *
 * ٣. **أوّلُ طلبٍ فقط.** «كوبونُ ترحيب» بلا هذا الشرط يستعمله عميلٌ
 *    قديمٌ في كل طلب.
 *
 * ── وغيابُ الصفّ يعني «بلا قيدٍ إضافيّ» لا «ممنوع» ───────────────
 *
 * فكوبونٌ بلا سياسةٍ يعمل بحدود Medusa وحدَها. وصفرٌ في `per_customer_limit`
 * كان سيعني «ممنوعٌ على الجميع» — وذاك قرارُ إطفاءٍ يُقال بـ`status`،
 * لا برقمِ حدٍّ يبدو حدّاً وهو إطفاء. فالقيدُ يمنع الصفر.
 */
export const CouponPolicy = model.define("zadim_coupon_policy", {
  id: model.id({ prefix: "cpnpol" }).primaryKey(),

  /** معرّفُ العرض في Medusa — واحدٌ لواحد. */
  promotion_id: model.text(),
  /** نسخةُ الرمز للقراءة — الدفترُ يبقى مقروءاً بعد حذف العرض. */
  promotion_code: model.text(),

  /** `null` = بلا حدٍّ لكل عميل. */
  per_customer_limit: model.number().nullable(),

  /** سقفُ الخصم بالهللات. `null` = بلا سقف. */
  max_discount: model.number().nullable(),

  /** يُقبل لمن لا طلبَ سابقاً له. */
  first_order_only: model.boolean().default(false),

  /**
   * ترتيبُ التطبيق — **رقمٌ يضبطه المدير لا سلوكٌ ضمنيّ**.
   *
   * وسببُه مقيس: محرّكُ Medusa يرتّب **بقيمة الخصم تنازلياً**، لا
   * «التلقائيُّ أوّلاً ثم الكوبون» كما تقول `01-domain-model.md` §٣.
   * فكوبونُ ٢٠٪ يُطبَّق قبل عرضٍ تلقائيٍّ ١٠٪، والنسبُ تتراكم على
   * الباقي — فيختلف الناتج.
   *
   * والرقمُ الأصغرُ يُطبَّق أوّلاً.
   */
  priority: model.number().default(100),
});

export default CouponPolicy;
