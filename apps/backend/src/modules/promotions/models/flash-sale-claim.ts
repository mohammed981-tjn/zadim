import { model } from "@medusajs/framework/utils";

/**
 * دفترُ مطالبات التخفيض الخاطف — **يُلحَق ولا يُمسّ**.
 *
 * ── ولماذا دفترٌ لا عدّاد ────────────────────────────────────────
 *
 * لأن العدّادَ حقلٌ مشتقٌّ يفسده التزاحم — وقد قِيس في هذا المستودع أن
 * قيداً عليه سمح بـ**٩٤ بيعاً من عشرة**. فالمتبقّي يُجمع من الصفوف تحت
 * قفلٍ عند كل مطالبة.
 *
 * ── والإلغاءُ صفٌّ مقابلٌ بكمّيةٍ سالبة ─────────────────────────
 *
 * لأن الدفاتر تُلحَق ولا تُمسّ. والإلغاءُ يقع فعلاً: تُطالَب القطعةُ
 * **قبل** إنشاء الطلب (الرفضُ قبل أخذ المال)، فإن سقط ما بعدها وجب
 * ردُّ القطعة إلى العرض. وحذفُ الصفّ كان يُخفي أن مطالبةً وقعت؛ والصفُّ
 * المقابل يُبقي الأثرَ ويُعيد السعة في آن.
 *
 * ولهذا `quantity` ليست موجبةً بالضرورة — وحارسُ القاعدة يفحص
 * الموجبةَ وحدَها: ردُّ قطعةٍ لا يحتاج إذناً.
 */
export const FlashSaleClaim = model.define("zadim_flash_sale_claim", {
  id: model.id({ prefix: "flashclm" }).primaryKey(),

  flash_sale_id: model.text(),

  /**
   * مفتاحُ العميل — **مطبَّعٌ** كما في منع الدفع عند الاستلام: جوّالٌ
   * بصيغتين عميلان في نظر أيّ قائمة، فيفلت الحدُّ بتغيير الكتابة.
   */
  customer_key: model.text(),

  /** السلّةُ التي طالبت — تُكتب قبل وجود الطلب. */
  cart_id: model.text(),
  /** يُملأ حين يقع الطلبُ فعلاً؛ و`null` لمطالبةٍ لم تكتمل بعد. */
  order_id: model.text().nullable(),

  /** موجبةٌ مطالبةٌ، وسالبةٌ ردّ. ولا تكون صفراً. */
  quantity: model.number(),

  /** سببُ الصفّ المقابل — يُقرأ في التدقيق. */
  reason: model.text().nullable(),
});

export default FlashSaleClaim;
