import { model } from "@medusajs/framework/utils";

/**
 * تخفيضٌ خاطف — **نافذةٌ وسقفُ كمّيةٍ فوق عرضِ Medusa** (بند ٢٨).
 *
 * ── ولا يُعاد بناءُ محرّك الخصم ──────────────────────────────────
 *
 * الخصمُ نفسُه عرضُ Medusa بقواعده وحساباته: نسبةً كان أو مبلغاً، على
 * صنفٍ أو سلّة. وما ينقص المحرّكَ ثلاثة، وكلُّها **سببُ وجود هذا
 * الجدول**:
 *
 * ١. **نافذةٌ زمنيةٌ يحرسها الخادم.** حملاتُ Medusa تملك نافذةً، لكنّ
 *    التخفيضَ الخاطف يُعرض بعدّادٍ تنازليٍّ في الواجهة — **ومؤقّتُ
 *    المتصفّح ليس مصدرَ الحقيقة**: ساعةُ الزائر تُضبط باليد، وصفحةٌ
 *    فُتحت قبل ساعةٍ تبقى مفتوحة. فالحكمُ عند الإتمام من ساعة القاعدة.
 *
 * ٢. **سقفُ كمّيةٍ للعرض نفسِه.** «أوّلُ مئةِ قطعة» ليس مخزوناً —
 *    المخزونُ ألفٌ والعرضُ لمئةٍ منها. و`limit` في Medusa عدّادُ
 *    استعمالاتٍ يُزاد بقراءةٍ ثم كتابة، ولا يعرف الكمّيات.
 *
 * ٣. **حدٌّ لكل عميل على العرض** — كسياسة الكوبون، لأن تخفيضاً خاطفاً
 *    بلا حدٍّ يشتريه واحدٌ كلَّه في دقيقة.
 *
 * ── والسقفُ لا يُخزَّن عدّاداً ──────────────────────────────────
 *
 * بل يُحسب من دفتر المطالبات. والدرسُ مدفوعُ الثمن في هذا المستودع:
 * `Migration20260901000002` أثبت أن قيداً على **عدّاد** لا يمنع شيئاً
 * (٩٤ بيعاً من ١٠)، لأن العدّادَ حقلٌ مشتقٌّ يفسده التزاحم. فالحقيقةُ
 * في الصفوف، والحارسُ يجمعها تحت قفل.
 */
export const FlashSale = model.define("zadim_flash_sale", {
  id: model.id({ prefix: "flash" }).primaryKey(),

  /** عرضُ Medusa الذي يحمل الخصمَ نفسَه — واحدٌ لواحد. */
  promotion_id: model.text(),
  /** نسخةُ الرمز للقراءة — الدفترُ يبقى مقروءاً بعد حذف العرض. */
  promotion_code: model.text(),

  starts_at: model.dateTime(),
  ends_at: model.dateTime(),

  /** سقفُ القطع. `null` = بلا سقفٍ كمّيّ (النافذةُ وحدَها تحكم). */
  quantity_limit: model.number().nullable(),

  /** `null` = بلا حدٍّ لكل عميل. */
  per_customer_limit: model.number().nullable(),

  /** إطفاءٌ فوريٌّ بيد المدير — أسرعُ من تعديل النافذة. */
  is_active: model.boolean().default(true),
});

export default FlashSale;
