import { model } from "@medusajs/framework/utils";

/**
 * استهلاكُ كوبون — بندُ ٢٦ وشطرُه من ٢٨ («العدّالة عند العدّ»).
 *
 * ولماذا جدولٌ عندنا وMedusa يعدّ الاستهلاكَ بنفسه: لأنه يعدّه **كلّياً
 * لا لكل عميل**. `promotion.limit` و`promotion.used` عدّادٌ واحدٌ
 * للكوبون كلِّه — يمنع «مئةَ استخدامٍ إجمالاً»، ولا يمنع أن يكون
 * المئةُ كلُّها لعميلٍ واحد.
 *
 * والحدُّ لكل عميل هو الحدُّ الذي يمنع الإساءةَ فعلاً: كوبونُ ترحيبٍ
 * حدُّه ألفٌ إجمالاً يستنزفه واحدٌ في ليلة.
 *
 * 🔴 **و`redemption_seq` ليس زينة.** هو ترتيبُ هذا الاستهلاك عند هذا
 * العميل (١، ٢، ٣…)، وعليه فهرسٌ فريد. فمحاولتان متزامنتان تحسبان
 * «التالي = ١» ⇒ إحداهما تصطدم بالفهرس وتسقط. وهذا هو ADR-014 نفسُه:
 * **التفرّدُ بقيدٍ لا بفحصٍ قبل الكتابة** — لأن «اقرأِ العدَّ ثم قرّر»
 * صحيحٌ في كل تشغيلةٍ منفردة وخاطئٌ في اثنتين معاً.
 */
export const CouponRedemption = model.define("zadim_coupon_redemption", {
  id: model.id({ prefix: "cpnred" }).primaryKey(),
  promotion_id: model.text(),
  // نسخةُ الرمز وقتَ الاستهلاك. والرمزُ يتغيّر أو يُحذف العرضُ، ويبقى
  // الدفترُ مقروءاً: «استُهلك WELCOME10» لا «استُهلك promo_01H…».
  promotion_code: model.text(),
  customer_id: model.text(),
  cart_id: model.text().nullable(),
  order_id: model.text().nullable(),
  /**
   * ⚠️ **القيمةُ المُرسَلةُ تُهمَل** — المُطلِقُ القبليُّ يحسبها
   * (`new.redemption_seq := v_used + 1`). والصفرُ هنا لأن MikroORM يطلب
   * الحقلَ قبل أن يصل المُطلِقَ أصلاً.
   *
   * ولماذا صفرٌ لا واحد: القيدُ `>= 1` يجعل الصفرَ **يسقط صاخباً** لو
   * اختفى المُطلِقُ يوماً — بدل أن يُكتب صفٌّ بترتيبٍ خاطئٍ صامتاً
   * فينكسر الحدُّ بلا أن يراه أحد.
   */
  redemption_seq: model.number().default(0),
});

export default CouponRedemption;
