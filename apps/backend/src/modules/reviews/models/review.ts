import { model } from "@medusajs/framework/utils";

/**
 * تقييمُ منتج (بند ٢٣) — **ويشترط الشراء بقيدٍ لا بفحصِ واجهة**.
 *
 * ── نصُّ البند ومصدرُه ───────────────────────────────────────────
 *
 * `01-domain-model.md`: «**التقييم يشترط الشراء**: `reviews.order_item_id`
 * إلزاميّ — فلا تقييمَ لمن لم يشترِ. **قيدٌ لا فحصُ واجهة**».
 *
 * وقِيس في 2026-09-03 أن **لا جدولَ `review` في القاعدة الحيّة**، وأن
 * ما كان مكتوباً في جدول التغطية «مُختبَر» كان على مخطَّط التصميم لا
 * على النظام العامل.
 *
 * ── ولماذا مُطلِقٌ لا مفتاحٌ أجنبيّ ─────────────────────────────
 *
 * مخطَّطُ المرحلة ٠ يكتبه مفتاحاً أجنبياً إلى `order_items`. وهو
 * **أضعفُ من المطلوب** ولا يمكن أخذُه كما هو:
 *
 * ١. `order_line_item` جدولُ Medusa، ويُحذف منه بسير عملٍ لا نملكه.
 *    و`ON DELETE RESTRICT` يجعل تقييماً **يمنع تعديلَ طلب**.
 * ٢. **والمفتاحُ الأجنبيُّ يتحقّق من الوجود وحدَه**: أن السطرَ موجود.
 *    ولا يتحقّق أنه **سطرُ هذا العميل**، ولا أنه **لهذا المنتج**. فمن
 *    يعرف معرّفَ سطرِ طلبِ غيره يكتب تقييماً باسمه، ومن اشترى قميصاً
 *    يقيّم به هاتفاً.
 *
 * فالمُطلِقُ يفحص الثلاثةَ معاً — وهو أقربُ إلى نيّة البند من حرفه.
 */
export const Review = model
  .define("zadim_review", {
    id: model.id({ prefix: "rev" }).primaryKey(),

    product_id: model.text(),
    customer_id: model.text(),

    /** سطرُ الطلب الذي يُثبت الشراء — **إلزاميّ**. */
    order_line_item_id: model.text(),

    rating: model.number(),
    body: model.text().nullable(),

    /**
     * `pending` افتراضاً — ومقصود.
     *
     * فالتقييمُ نصٌّ يكتبه الجمهورُ ويُعرض على صفحة منتجٍ تُفهرَس. ونشرٌ
     * فوريٌّ بلا مراجعةٍ يجعل المتجرَ لوحةَ إعلاناتٍ لمن يكتب روابطَ
     * ورقمَ واتساب.
     */
    status: model.enum(["pending", "published", "rejected"]).default("pending"),

    /** سببُ الرفض — يُقال لصاحبه ولا يُترك يخمّن. */
    moderation_note: model.text().nullable(),
  })
  .indexes([
    // تقييمٌ واحدٌ لكل بندٍ اشتُري (نصُّ المخطَّط: `UNIQUE (order_item_id,
    // customer_id)`). ومن اشترى الصنفَ مرّتين يقيّمه مرّتين — وهي حالٌ
    // صحيحة: تجربتان في وقتين.
    {
      on: ["order_line_item_id", "customer_id"],
      unique: true,
      where: "deleted_at IS NULL",
    },
    { on: ["product_id", "status"] },
  ]);

export default Review;
