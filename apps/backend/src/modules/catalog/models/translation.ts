import { model } from "@medusajs/framework/utils";

/**
 * ترجمةُ حقلٍ واحدٍ من كيانٍ واحدٍ إلى لغةٍ واحدة (المرحلة ١١ب).
 *
 * ── لماذا جدولٌ لا أعمدةٌ في جدول المنتجات ───────────────────────
 *
 * لأن جدولَ المنتجات ليس ملكَنا: هو جدولُ Medusa، وكلُّ عمودٍ نضيفه
 * إليه دَينٌ نسدّده في كل ترقية. ولأن `title_en` عمودٌ يعني أن اللغةَ
 * الثالثة **هجرةٌ تعدّل جدولاً حيّاً**، بينما هنا هي صفوفٌ جديدة.
 *
 * ── والمفتاحُ رباعيّ: (نوع · معرّف · حقل · لغة) ───────────────────
 *
 * فترجمتان لنفس الحقل بنفس اللغة ليستا خياراً بين نصّين، بل **عطلٌ
 * صامت**: أيُّهما يظهر يقرّره ترتيبُ الصفوف — أي لا شيء. والفهرسُ
 * الفريدُ الجزئيّ يجعل الثانيةَ خطأً وقتَ الكتابة لا مفاجأةً وقتَ
 * العرض.
 *
 * ── 🔴 وأخطرُ ما في الجدول: أيُّ حقلٍ يُسمح بترجمته ───────────────
 *
 * `handle` و`status` و`sku` نصوصٌ في نظر قاعدة البيانات، وترجمتُها
 * تعني رابطاً مكسوراً أو منتجاً يختفي من المتجر. ولو تُرك الحقلُ
 * مفتوحاً لكان بابَ تخريبٍ لا ترجمة.
 *
 * فالمسموحُ **قائمةٌ محصورة** في قيدٍ داخل القاعدة لا في تحقّقٍ داخل
 * المسار: التحقّقُ في المسار يحرس البابَ الذي يعرفه، والقيدُ يحرس
 * الجدولَ من كلِّ باب — بما فيها سكربتٌ يكتب مباشرةً بعد سنة.
 *
 * ── والقيمةُ الفارغة ممنوعة ──────────────────────────────────────
 *
 * لأن الفارغةَ تُمحو النصَّ الأصليّ بدل أن تحلّ محلَّه: صفحةٌ بلا
 * عنوان. وغيابُ الترجمة يعرض الأصلَ العربيّ — وهو أسوأُ من الإنجليزية
 * وأفضلُ بكثيرٍ من الفراغ.
 */
export const Translation = model.define("zadim_translation", {
  id: model.id({ prefix: "trn" }).primaryKey(),
  entity_type: model.enum([
    "product",
    "product_variant",
    "product_category",
    "product_collection",
    "cms_block",
  ]),
  // لا مفتاحَ أجنبيّ: الكياناتُ في وحدة منتجات Medusa، والعبورُ بين
  // الوحدات لا يكون بـFK (نفسُ سببِ `zadim_seo_meta`).
  entity_id: model.text(),
  field: model.text(),
  locale: model.text(),
  value: model.text(),
}).indexes([
  { on: ["entity_type", "entity_id", "field", "locale"], unique: true },
  // فهرسُ القراءة: المُلبِسُ يقرأ بـ(معرّف · لغة) لدفعةٍ كاملةٍ من
  // المعرّفات في استعلامٍ واحد — لا استعلامٍ لكل منتج.
  { on: ["locale", "entity_id"] },
]);

export default Translation;
