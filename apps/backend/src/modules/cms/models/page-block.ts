import { model } from "@medusajs/framework/utils";

/**
 * كتلةٌ في صفحة — **الرئيسيةُ بياناتٌ لا كود** (بند ١).
 *
 * ── لماذا الترتيبُ في القاعدة ───────────────────────────────────
 *
 * بوّابةُ المرحلة ٩: «ترتيبُ الرئيسية يتغيّر من اللوحة **بلا نشرِ
 * كود**». ورئيسيةٌ مبنيّةٌ في JSX تعني أن تقديمَ قسمٍ على قسمٍ في موسم
 * التخفيضات **نشرةُ إصدار**: مبرمجٌ يعدّل، ومراجعةٌ، وبناءٌ، ونشرٌ —
 * لتحريكِ صندوقٍ إلى أعلى.
 *
 * فالصفحةُ صفوفٌ مرتّبة، والواجهةُ تعرضها كما جاءت.
 *
 * ── و`payload` مفتوحٌ عمداً ─────────────────────────────────────
 *
 * لكل نوعِ كتلةٍ حقولُه، وجدولٌ بأعمدةٍ لكل نوعٍ يعني هجرةً لكل كتلةٍ
 * جديدة. والواجهةُ **تتجاهل النوعَ الذي لا تعرفه** ولا تنهار — فيُضاف
 * النوعُ في القاعدة قبل أن تعرفه الواجهة، ويظهر يوم تُنشر.
 */
export const PageBlock = model.define("zadim_page_block", {
  id: model.id({ prefix: "blk" }).primaryKey(),

  /** الصفحة: `home` اليوم، وغيرُها لاحقاً بلا هجرة. */
  page: model.text().default("home"),

  type: model.text(),
  /** الأصغرُ أعلى. */
  position: model.number().default(0),
  is_active: model.boolean().default(true),

  /** اسمٌ داخليٌّ للمدير — لا يُعرض للعميل. */
  name_ar: model.text().nullable(),
  payload: model.json().nullable(),
}).indexes([
  { on: ["page", "position"] },
]);

export default PageBlock;
