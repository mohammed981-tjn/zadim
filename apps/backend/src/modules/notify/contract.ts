import type { SendPlan } from "../marketing/dispatcher";

/**
 * عقدُ مزوّد الإشعارات (بند ٤٣).
 *
 * ── لماذا `status` لا `ok` ──────────────────────────────────────
 *
 * 🔴 لأن **«نجح» و«وصل» ليسا واحداً**، والخلطُ بينهما هو العطبُ الذي
 * تمنعه هذه الطبقة. كان `dispatch` يترجم `ok:true` إلى `sent` — فأيُّ
 * مزوّدٍ يقول «تلقّيتُ طلبَك» يُسجَّل «أُرسلت». ثم يُبنى على ذلك تقريرٌ
 * يقول إن ٩٩٪ من الرسائل وصلت، ثم قرارٌ على التقرير.
 *
 * والمزوّدُ هو من يعرف: مزوّدٌ يسجّل ولا يرسل يقول `queued`، ومزوّدٌ
 * سلّم الرسالةَ إلى خادم بريدٍ يقول `sent`. **ولا أحدَ يُترجم عنه**.
 *
 * ⚠️ **و`sent` تعني «سُلّمت إلى المزوّد» لا «قرأها العميل»** — وهذا
 * أقصى ما يمكن معرفتُه لحظةَ الإرسال. وما بعده (فُتحت · ارتدّت) يصل
 * بخطّافٍ من المزوّد لا من هنا، ولم يُبنَ بعد.
 */
export type SendOutcome = {
  /**
   * `sent` — سُلّمت إلى المزوّد.
   * `queued` — قُبلت ولم تُسلَّم بعد (وهي حالُ المزوّد المسجِّل).
   * `failed` — رُفضت، و`error` يقول لماذا.
   */
  status: "sent" | "queued" | "failed";
  provider: string;
  error?: string;
};

export interface NotifyProvider {
  /** معرّفٌ يُسجَّل في `zadim_notification_send.provider`. */
  readonly id: string;
  /** القنواتُ التي يخدمها — ومزوّدُ بريدٍ لا يُنادى لرسالةٍ نصّية. */
  readonly channels: ReadonlyArray<SendPlan["channel"]>;
  send(plan: SendPlan): Promise<SendOutcome>;
}
