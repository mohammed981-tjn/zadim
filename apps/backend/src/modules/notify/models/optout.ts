import { model } from "@medusajs/framework/utils";

/**
 * إلغاءُ الاشتراك — **الحارسُ الذي يجعل طبقةَ الإشعارات مشروعة**.
 *
 * ── ولماذا مع المزوّد لا بعده ───────────────────────────────────
 *
 * لأن اليومَ الذي يبدأ فيه الإرسالُ الفعليُّ هو اليومُ الذي يجب أن
 * يعمل فيه الإلغاء. ورسائلُ تسويقٍ بلا مخرجٍ ليست خياراً تقنياً
 * مؤجَّلاً: هي شكوى، ثم حظرُ نطاقِ المتجر عند مزوّدي البريد — وذلك
 * **لا يُستدرَك بإصلاحِ كود**، لأن السمعةَ تُبنى شهوراً.
 *
 * فيصل مع المزوّد لا بعده بدفعة. و`zadim_notification_send.status`
 * يحمل `suppressed` منذ المرحلة ١١ **ولا شيءَ كان يضعها** — وهذا ما
 * يملؤها.
 *
 * ── والمفتاحُ (القناة · المستقبِل) لا العميل ────────────────────
 *
 * لأن من يُلغي **بريدَه** قد يبقى راضياً عن الرسائل النصّية، والعكس.
 * ولأن المستقبِلَ قد لا يكون عميلاً مسجَّلاً أصلاً: الضيفُ الذي ترك
 * سلّةً يُراسَل ولا حسابَ له، وحقُّه في الإلغاء كحقّ المسجَّل.
 */
export const NotificationOptout = model
  .define("zadim_notification_optout", {
    id: model.id({ prefix: "nopt" }).primaryKey(),

    channel: model.text(),
    /** البريدُ أو الجوّال — **مطبَّعاً** كما يُبنى مفتاحُ الإرسال. */
    recipient: model.text(),

    /** «لماذا» — طلبُ العميل، أو ارتدادٌ متكرّر، أو شكوى. */
    reason: model.text().default("requested"),
  })
  .indexes([
    // 🔴 فريدٌ لا «اقرأ ثمّ اكتب»: ضغطتان على رابط الإلغاء تصلان معاً،
    // والقيدُ يجعل الثانيةَ تصطدم بدل أن تُنشئ صفّاً ثانياً.
    { on: ["channel", "recipient"], unique: true, where: "deleted_at IS NULL" },
  ]);

export default NotificationOptout;
