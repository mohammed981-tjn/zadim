import { model } from "@medusajs/framework/utils";

/**
 * سياسةُ إعادة المحاولة — **بيانات لا كود** (بند ٤٨).
 *
 * ── لماذا سياسةٌ لا ثابتٌ في الكود ───────────────────────────────
 *
 * «ثلاثُ محاولاتٍ ثم يُشطب» يبدو رقماً هندسياً، وليس كذلك: هو موازنةٌ
 * بين رسالةٍ تضيع لأن المزوّدَ كان ساقطاً دقيقتين، وطابورٍ يظلّ يطرق
 * بابَ عنوانٍ لم يعد موجوداً فيُحرق نطاقُ المتجر عند مزوّدي البريد.
 * وحدُّ الاثنين قرارُ مالكٍ يتغيّر مع المزوّد الذي يُختار.
 *
 * ── والمهلةُ كذلك ───────────────────────────────────────────────
 *
 * إعادةٌ فوريّةٌ بعد فشلٍ تُعيد الاصطدامَ بنفس السبب: المزوّدُ الساقطُ
 * قبل ثانيةٍ ساقطٌ الآن. والمهلةُ تُضاعَف مع كل محاولة
 * (`retry_after_seconds × attempts`) فلا تُغرق مزوّداً يتعافى.
 *
 * ⚠️ **وصفٌّ واحدٌ يحرسه فهرسٌ فريد**: سياستان تعنيان أن السلوكَ يتبع
 * أيَّهما قرأ الكودُ أوّلاً — وهو أسوأُ من غياب السياسة، لأنه يتغيّر
 * بلا سبب.
 */
export const NotifyPolicy = model.define("zadim_notify_policy", {
  id: model.id({ prefix: "npol" }).primaryKey(),

  /** كم محاولةً قبل الشطب. بلوغُها يعني `dead` ولا عودة. */
  max_attempts: model.number().default(3),

  /** أساسُ المهلة بالثواني — تُضرب في رقم المحاولة. */
  retry_after_seconds: model.number().default(300),

  /** إيقافُ الإعادة كلَّها — لتشخيصِ عطلٍ بلا إغراقِ مزوّد. */
  is_enabled: model.boolean().default(true),

  note: model.text().nullable(),
});

export default NotifyPolicy;
