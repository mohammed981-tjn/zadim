import { model } from "@medusajs/framework/utils";

/**
 * البائع — **موجودٌ ومعطَّل** (بند ٥٩).
 *
 * ── لماذا يُنشأ اليوم ومتجرُنا بائعٌ واحد ─────────────────────────
 *
 * لأن `07-roadmap.md` يضع «`vendor_id` في الجداول» في جدول **«ما لا
 * يُؤجَّل مهما ضاق الوقت»**، وحجّتُه: «**إضافتُه على مليون صفٍّ هجرةٌ
 * تُوقف المتجر**». وعمودٌ يُضاف على `product` و`order` وهما فارغان
 * كلفتُه ثوانٍ؛ ويوم يحمل كلٌّ منهما مئاتِ الألوف يصير `ALTER TABLE`
 * قفلاً على جدولٍ يبيع.
 *
 * وقِيس على القاعدة الحيّة في 2026-09-03 أن الجدولَ **ليس موجوداً**
 * وأن `vendor_id` عمودٌ واحدٌ يتيمٌ في `zadim_user_role` — وهو **نطاقُ
 * دورٍ لا ملكيّةُ صفّ**، أي شيءٌ آخر تماماً.
 *
 * ── وما معنى «معطَّل» بالضبط ─────────────────────────────────────
 *
 * أن الأعمدةَ موجودةٌ وقابلةٌ للعدم، **ولا مسارَ يقرؤها ولا يكتبها**.
 * فمتجرُ اليوم يعمل كما كان بلا سطرٍ واحدٍ يتغيّر في منطقه، ويوم
 * يُفتَح السوقُ يكون الحقلُ قد رافق كلَّ صفٍّ من أوّل يوم.
 *
 * ⚠️ **ولا صفَّ افتراضيّاً يُبذَر هنا.** «بائعٌ اسمه زادم» يجعل
 * الأعمدةَ ممتلئةً بقيمةٍ لا معنى لها، فيظنّ من يقرؤها لاحقاً أن
 * الميزةَ تعمل. والعدمُ أصدقُ: **لا بائعَ لأن السوقَ لم يُفتح**.
 */
export const Vendor = model.define("zadim_vendor", {
  id: model.id({ prefix: "vend" }).primaryKey(),

  name: model.text(),
  /** الاسمُ في المسار — `/vendors/:handle`. */
  handle: model.text().unique(),

  /** السجلُّ التجاريّ والرقمُ الضريبيّ — لازمان للفوترة باسم البائع. */
  cr_number: model.text().nullable(),
  vat_number: model.text().nullable(),

  contact_email: model.text().nullable(),
  contact_phone: model.text().nullable(),

  /**
   * عمولةُ المنصّة **بنقاطٍ أساس** (١٠٠ = ١٪) لا كسراً عشرياً — نفسُ
   * قاعدة الهللات (ADR-008): الكسورُ العشرية تتراكم أخطاؤها على المال.
   */
  commission_bps: model.number().default(0),

  /** معطَّلٌ افتراضاً: بائعٌ يُنشأ لا يبيع حتى يُعتمد. */
  is_active: model.boolean().default(false),

  note: model.text().nullable(),
});

export default Vendor;
