import { model } from "@medusajs/framework/utils";

/**
 * تكلفةُ الوحدة الحاليّة لمتغيّرٍ — **سجلُّ تكلفةٍ لا عمودٌ على المنتج**.
 *
 * ── لماذا جدولٌ مستقلّ لا عمودٌ في `product_variant` ───────────────
 *
 * لأن التكلفةَ **تتغيّر** والسعرَ لا يتغيّر بها: يُشترى الصنفُ اليوم
 * بعشرين وغداً بأربعةٍ وعشرين، ويُباع بالسعر نفسِه. وعمودٌ واحدٌ على
 * المتغيّر يحمل رقماً واحداً — فمن كتب الرقمَ الجديد **محا القديم**،
 * وضاع معه ربحُ ما بيع قبل اليوم.
 *
 * وهذا الجدولُ يحمل **التكلفةَ النافذة الآن** وحدَها، وتاريخُه يبقى
 * صفوفاً لا تُحدَّث: كلُّ تغييرٍ صفٌّ جديدٌ بـ`effective_from`، والصفُّ
 * السابق يُغلق بـ`effective_to`. فسؤالُ «بكم كان يكلّفنا في رمضان؟»
 * له جوابٌ لا تخمين.
 *
 * ⚠️ **ولا يُقرأ هذا الجدولُ عند حساب ربحِ طلبٍ ماضٍ.** الطلبُ يحمل
 * تكلفتَه مجمَّدةً في سطره (`order_line_item.unit_cost`) لحظةَ وقوعه.
 * وهذا الجدولُ مصدرُ التجميد لا بديلُه: يُقرأ **مرّةً** حين يُنشأ
 * السطر، ثم لا يُقرأ له أبداً. ولو حُسب الربحُ منه لتغيّر ربحُ يناير
 * كلّما تغيّرت فاتورةُ المورّد في مارس — وهو بالضبط ما يمنعه بند
 * «`unit_cost` المُجمَّدة» في جدول «ما لا يُؤجَّل».
 *
 * وبالهللات صحيحةً لا كسوراً عشرية (ADR-008).
 */
export const VariantCost = model.define("zadim_variant_cost", {
  id: model.id({ prefix: "vcost" }).primaryKey(),

  variant_id: model.text(),

  /** تكلفةُ الوحدة بالهللات. صفرٌ مسموحٌ (هديّة/عيّنة)، والسالبُ ممنوعٌ بقيد. */
  unit_cost: model.number(),

  /** «من أين جاء هذا الرقم» — فاتورةُ مورّدٍ، أو إدخالٌ يدويّ، أو استيراد. */
  source: model.text().default("manual"),

  effective_from: model.dateTime(),
  /** `null` = هي النافذة الآن. */
  effective_to: model.dateTime().nullable(),

  note: model.text().nullable(),
});

export default VariantCost;
