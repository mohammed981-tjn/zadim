import { model } from "@medusajs/framework/utils";

/**
 * سطرُ فحصٍ — **الشهادةُ التي يقف عليها كلُّ ما بعدها**.
 *
 * ── لماذا لا يكفي `return_item.damaged_quantity` عند Medusa ──────
 *
 * فحصتُ الكيان: فيه `received_quantity` و`damaged_quantity` **رقمين
 * مجرّدين** — بلا فاحصٍ، ولا سبب، ولا وقت، ولا نتيجةٍ أدقَّ من
 * «تالف/غيرُ تالف». ولا يفرّق بين **ناقصٍ** لم يصل و**تالفٍ** وصل،
 * وبين **صنفٍ خطأ** أُرسل مكانه. والفرقُ ليس وصفياً: الناقصُ مطالبةٌ
 * على الناقل، والتالفُ خسارةُ متجر، والخطأُ خطأُ لقطٍ في المستودع.
 *
 * فهذا السطرُ يُجيب أربعة: **ما الذي فُحص · وكم · وما نتيجتُه · ومن
 * حكم**.
 *
 * ── ولا يُعدَّل ولا يُحذف ────────────────────────────────────────
 *
 * قاعدةُ `DO INSTEAD NOTHING` في الهجرة، كدفتر الحركات وسجلّ التدقيق.
 * وشهادةٌ تُعدَّل بعد أن يُبنى عليها استردادٌ ورجوعُ بضاعةٍ إلى الرفّ
 * **ليست شهادة**: من أعاد تالفاً إلى الرفّ يستطيع أن يمحوَ الحكمَ
 * ويكتب «سليم».
 *
 * ── والكمّيةُ لا النِّسبة ────────────────────────────────────────
 *
 * مرتجعٌ من ثلاثِ قطعٍ قد يكون: اثنتان سليمتان وواحدةٌ تالفة. فالفحصُ
 * **سطورٌ لا سطر**، والمُطلِقُ يجمعها ليقرّر كم يُطلَق إلى الرفّ.
 */
export const ReturnInspection = model.define("zadim_return_inspection", {
  id: model.id({ prefix: "rinsp" }).primaryKey(),

  // معرّفاتُ جداولِ وحدةٍ أخرى (`return` عند Medusa) — نصٌّ بلا مفتاحٍ
  // أجنبيّ، كما في بقية وحداتنا: ربطُ الوحدات عند Medusa بالروابط.
  return_id: model.text(),
  return_item_id: model.text().nullable(),
  inventory_item_id: model.text().nullable(),

  quantity: model.number(),

  /**
   * `resellable` — وحدَها تفتح بابَ الرفّ.
   * `damaged` · `missing` · `wrong_item` — لا تفتح شيئاً أبداً.
   */
  outcome: model.enum(["resellable", "damaged", "missing", "wrong_item"]),

  /** **إلزاميّ**: حكمٌ بلا سبب لا يُراجَع ولا يُتعلَّم منه. */
  reason_ar: model.text(),

  /** من فحص. والفحصُ **بشريّ** — وهذا الحقلُ هو ما يجعله كذلك. */
  actor_id: model.text().nullable(),

  /** كم أُطلق فعلاً إلى الرفّ من هذا السطر — يمنع الإطلاقَ مرّتين. */
  released_quantity: model.number().default(0),
}).indexes([
  { on: ["return_id"] },
  { on: ["outcome"] },
]);

export default ReturnInspection;
