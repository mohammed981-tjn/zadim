import { model } from "@medusajs/framework/utils";

/**
 * سياسةُ تسوية المخزون — **بيانات لا كود** (بند ٤٨).
 *
 * ── ولماذا حدٌّ أصلاً، ولماذا حدّان ──────────────────────────────
 *
 * لأن اشتراطَ موافقةٍ ثانيةٍ على **كلّ** تسويةٍ يقتل التسويةَ نفسَها:
 * موظّفُ المستودع الذي يجد قطعةً مكسورةً يحتاج مديراً لكلّ قطعة، فلا
 * يسجّل شيئاً — ويصير الرقمُ في الشاشة أبعدَ عن الرفّ من قبل. **وحارسٌ
 * يُتجاوَز أسوأُ من حارسٍ غائب**، لأنه يمنح ثقةً بلا مقابل.
 *
 * ── والحدُّ بالكمّية **وبالقيمة** معاً ──────────────────────────
 *
 * 🔴 وهذا هو الفرق الذي يُغفَل: «عشرُ قطعٍ» حدٌّ معقولٌ لأقلامٍ ثمنُ
 * القطعة ريال، **وبابٌ مفتوحٌ** لهواتفَ ثمنُ القطعة ثلاثةُ آلاف. ومن
 * أراد السرقةَ يختار الغالي.
 *
 * فالتجاوزُ **أيُّهما وقع أوّلاً**: الكمّيةُ أو القيمة. والقيمةُ تُحسب
 * من التكلفة المجمَّدة، وصنفٌ بلا تكلفةٍ يُعامَل بحدّ الكمّية وحدَه
 * ويُقال ذلك.
 */
export const AdjustmentPolicy = model.define("zadim_adjustment_policy", {
  id: model.id({ prefix: "adjp" }).primaryKey(),

  /** فوق هذه الكمّية (بالقيمة المطلقة) تلزم موافقةٌ ثانية. */
  threshold_quantity: model.number().default(10),

  /** أو فوق هذه القيمة بالهللات — أيُّهما وقع أوّلاً. */
  threshold_value_halalas: model.number().default(50000),

  /** إيقافُ التسوية اليدوية كلِّها — لجردٍ مقفلٍ مثلاً. */
  is_enabled: model.boolean().default(true),

  note: model.text().nullable(),
});

export default AdjustmentPolicy;
